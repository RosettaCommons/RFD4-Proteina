# Absolute path to the baselines directory regardless of cwd.
BASELINES_DIR = Path(__file__).resolve().parents[1] / "baselines"

_DATA_PATH = os.environ.get("DATA_PATH", "").strip()


def _resolve_sota_ckpt_path() -> Path | None:
    """Resolve the SOTA checkpoint from configs/inference.yaml, the single source of truth.

    Reads ckpt_path/ckpt_name from that config (built-in ``oc.env`` resolves ``$DATA_PATH``;
    no custom resolvers needed) so inference and the regression suite always pin the same file.
    Returns ``None`` if ``$DATA_PATH`` is unset, so ``require_sota_ckpt`` can fail with a clear message.
    """
    if not _DATA_PATH:
        return None
    inference_yaml = Path(__file__).resolve().parents[3] / "configs" / "inference.yaml"
    cfg = OmegaConf.load(inference_yaml)
    ckpt_path = OmegaConf.select(cfg, "ckpt_path")  # resolves ${oc.env:DATA_PATH}
    ckpt_name = OmegaConf.select(cfg, "ckpt_name")
    return Path(ckpt_path) / ckpt_name


# SOTA checkpoint: read from configs/inference.yaml so generate.py and these baselines pin the
# same immutable, named file (not the moving "latest.ckpt" symlink). Published in the public bucket
# s3://YOUR_DATASET_STORE/latent_checkpoints/ldm_checkpoints/ (fetch it with
# scripts/download_example_data.sh -- no credentials). Baselines are regenerated against this
# exact file (see src/script_utils/generate_e2e_baselines.py); to advance SOTA, edit inference.yaml.
SOTA_CKPT_PATH = _resolve_sota_ckpt_path()
# Single MCSA example used for all inference regression tests.
REGRESSION_EXAMPLE_ID = "M0664_2dhn"

# Beam search runs the smallest unindexed motif in benchmarks/motif_unindexed
# (3IXT, motif P254-277) and ranks candidates on how closely they reproduce that motif.
BEAM_SEARCH_EXAMPLE = "3IXT_AA"
BEAM_SEARCH_REWARD_KEY = "design_unindexed_motif_allatom_rmsd.rmsd"

# Shared by the regression test and the baseline generator so the two cannot drift.
BEAM_SEARCH_OVERRIDES = [
    "inference_experiment=inference_beam_regression",
    "~metrics/refolding_oracles",
    "inputs=${oc.env:PROJECT_ROOT}/data/benchmarks/motif_unindexed",
    f"subset_to_examples={BEAM_SEARCH_EXAMPLE}",
    "++metrics_tags=[design,unindexed]",
    "++search.rewards.reward_metrics_tags=[design,unindexed]",
    # The motif reward is a design metric, so no oracle is needed and this stays fast. The zero
    # weight neutralises the inherited clash term: hydra cannot delete a key containing dots,
    # and aggregate_metrics_output skips falsy weights.
    f"++search.rewards.weights={{clash_metrics.frac_atoms_clashing_1p5A: 0.0, {BEAM_SEARCH_REWARD_KEY}: -1.0}}",
    # 20 steps is too few here: the insertion mapping goes infeasible for reasons unrelated to
    # what this guards, which would mask a real regression behind a spurious failure.
    "generation.args.nsteps=100",
    "search.strategy.step_checkpoints=[0,50,100]",
    "search.strategy.n_branch=2",
    "search.strategy.beam_width=2",
    "num_replicates=1",
    # Pin val_set_name_override so the val set is named the same on every machine,
    # regardless of where the inputs are mounted.
    "generation.val_set_name_override=beam_example",
    "seed=42",
    "torch_deterministic=true",
    # No compilation for regression tests.
    "compile_lengths=null",
]

# Tolerances.
# Per-step early-exit threshold: kill the training subprocess as soon as any
# single step deviates by more than this (catches hard regressions fast).
LOSS_ATOL_PER_STEP = 0.2
# Mean absolute deviation threshold: applied after all steps complete to catch
# systematic drift that stays below the per-step limit on every individual step.
LOSS_ATOL_MEAN = 0.05
BASELINE_RMSD_ATOL_TIGHT = 0.20  # Å — all-atom RMSD for deterministic outputs (inference)
BEAM_SEARCH_RMSD_ATOL = 0.05  # Å — motif RMSD drift for a deterministic beam-search run
METRIC_ATOL = 1e-3  # pLDDT / ptm / iptm for deterministic outputs


def load_design_cif(path: Path | str) -> AtomArray:
    """Load a design CIF with all annotations"""
    return parse(str(path), config=DISTILLATION)["asym_unit"][0]


def deterministic_env() -> dict[str, str]:
    """Env vars that make CUDA operations reproducible on the same hardware."""
    env = os.environ.copy()
    # Fix MASTER_PORT: the cluster env file sets it to a bash expression Python can't evaluate.
    env.setdefault("MASTER_PORT", "29500")
    # Fix PYTHONPATH: the venv has a 'scripts' package that shadows the project's scripts/.
    project_root = str(Path(__file__).resolve().parents[3])
    existing = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = f"{project_root}:{existing}" if existing else project_root
    env["CUBLAS_WORKSPACE_CONFIG"] = ":4096:8"
    env["CUBLAS_DETERMINISTIC"] = "1"
    env["PYTHONHASHSEED"] = "0"
    env["WANDB_MODE"] = "disabled"
    return env


def require_h200() -> None:
    """Skip unless running on an H200; baselines are generated on cw-west and are GPU-specific."""
    try:
        out = subprocess.check_output(["nvidia-smi", "-L"], text=True, timeout=10)
    except (FileNotFoundError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
        pytest.skip("nvidia-smi unavailable; cannot verify H200")
    if "H200" not in out:
        pytest.skip(f"Baselines are H200-specific; detected: {out.strip()!r}")


def require_sota_ckpt() -> None:
    if SOTA_CKPT_PATH is None:
        pytest.fail("DATA_PATH is not set; cannot resolve the SOTA checkpoint from configs/inference.yaml")
    if not SOTA_CKPT_PATH.is_file():
        pytest.fail(
            f'SOTA checkpoint not found: {SOTA_CKPT_PATH}. Fetch it with ./scripts/download_example_data.sh "$DATA_PATH"'
        )


def load_baseline_losses(name: str) -> list[float]:
    """Load reference step losses from baselines/<name>/losses.json.

    Skips the test if the file is missing (baselines not yet generated).
    """
    path = BASELINES_DIR / name / "losses.json"
    if not path.is_file():
        pytest.fail(
            f"Baseline losses not found: {path}. Run src/script_utils/generate_e2e_baselines.py to generate them."
        )
    return json.loads(path.read_text())["losses"]


def all_atom_rmsd(cif_path_a: Path, cif_path_b: Path) -> float:
    """Compute all-atom RMSD between two CIF structures after rigid superposition."""
    atoms_a = load_design_cif(cif_path_a)
    atoms_b = load_design_cif(cif_path_b)
    if len(atoms_a) != len(atoms_b):
        raise ValueError(
            f"Atom count mismatch: {cif_path_a.name} has {len(atoms_a)} atoms, {cif_path_b.name} has {len(atoms_b)}"
        )
    fitted, _ = superimpose(atoms_b, atoms_a)
    return float(rmsd(atoms_b, fitted))


def find_inference_cif(out_dir: Path, example_id: str, kind: str) -> Path:
    """Glob for a designed or refolded CIF under out_dir.

    Args:
        kind: ``"generated"`` or ``"af3_refolded"``.
    """
    pattern = f"**/*{example_id}*_{kind}.cif"
    matches = list(out_dir.rglob(f"*{example_id}*_{kind}.cif"))
    if not matches:
        raise FileNotFoundError(f"No CIF matching {pattern!r} under {out_dir}")
    return matches[0]


def find_beam_search_cifs(out_dir: Path) -> list[Path]:
    """Return all generated CIFs found under out_dir (beam search), sorted."""
    matches = sorted(out_dir.rglob("*_generated.cif"))
    if not matches:
        raise FileNotFoundError(f"No *_generated.cif found under {out_dir}")
    return matches


def find_oracle_refolded_cif(out_dir: Path, oracle_name: str) -> Path:
    """Return the refolded CIF produced by evaluate.py for the given oracle.

    evaluate.py writes oracle outputs under ``out_dir/evaluation_samples/`` in the
    design's own subdirectory.  Since we evaluate a single design, there is
    exactly one match.

    Args:
        out_dir: The ``out_dir`` passed to evaluate.py.
        oracle_name: Oracle label, e.g. ``"af3"``.
    """
    matches = sorted((out_dir / "evaluation_samples").rglob(f"*_{oracle_name}_refolded.cif"))
    if not matches:
        raise FileNotFoundError(f"No *_{oracle_name}_refolded.cif found under {out_dir / 'evaluation_samples'}")
    return matches[0]


def beam_search_motif_rmsds(out_dir: Path) -> list[float]:
    """Return each final design's motif RMSD from a beam-search run, ascending.

    This is what the beam-search baseline pins instead of whole CIFs: it tracks the same
    coordinates without committing ~200 KB of generated structure per design.
    """
    csv_files = list((out_dir / "inference_metrics").glob("per_example_metrics*.csv"))
    if not csv_files:
        return []
    df = pd.read_csv(max(csv_files))
    if BEAM_SEARCH_REWARD_KEY not in df.columns or "example_id" not in df.columns:
        return []
    rows = df[df["example_id"].astype(str).str.contains(BEAM_SEARCH_EXAMPLE, regex=False)]
    return sorted(float(v) for v in rows[BEAM_SEARCH_REWARD_KEY] if not _is_nan(v))


def parse_per_example_metrics(
    out_dir: Path,
    example_id: str,
    *,
    oracle_only: bool = True,
) -> dict:
    """Read per-example metrics for example_id from the inference_metrics CSV.

    The CSV ``example_id`` column contains a hash-suffixed value like
    ``M0664_2dhn_0_8b2985``; we match by substring so callers can pass
    the bare example key (e.g. ``"M0664_2dhn"``).

    Args:
        oracle_only: If True (default), return only ``oracle.*`` columns.
    """
    csv_files = list((out_dir / "inference_metrics").glob("per_example_metrics*.csv"))
    if not csv_files:
        return {}
    df = pd.read_csv(sorted(csv_files)[-1])
    if "example_id" not in df.columns:
        return {}
    mask = df["example_id"].astype(str).str.contains(example_id, regex=False)
    rows = df[mask]
    if rows.empty:
        return {}
    row = rows.iloc[0]
    result: dict[str, float] = {}
    for col in df.columns:
        if oracle_only and not col.startswith("oracle."):
            continue
        if not _is_nan(row.get(col)):
            result[col] = float(row[col])
    return result


def parse_evaluate_metrics(out_dir: Path, *, oracle_only: bool = True) -> dict[str, float]:
    """Read per-example metrics from an evaluate.py output directory.

    evaluate.py writes a single CSV to ``evaluation_metrics/`` containing one
    row per evaluated structure.  This helper returns the first row, which is
    correct when only one structure was evaluated (as in the regression tests).

    Args:
        oracle_only: If True (default), return only ``oracle.*`` columns.
    """
    csv_files = list((out_dir / "evaluation_metrics").glob("per_example_metrics*.csv"))
    if not csv_files:
        return {}
    df = pd.read_csv(sorted(csv_files)[-1])
    if df.empty:
        return {}
    row = df.iloc[0]
    result: dict[str, float] = {}
    for col in df.columns:
        if oracle_only and not col.startswith("oracle."):
            continue
        if not _is_nan(row.get(col)):
            result[col] = float(row[col])
    return result


def _is_nan(v: object) -> bool:
    try:
        return np.isnan(float(v))
    except (TypeError, ValueError):
        return True
