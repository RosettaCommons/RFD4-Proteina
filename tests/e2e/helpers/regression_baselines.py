"""Helpers for loading and comparing GPU regression test baselines.

Baselines live in tests/e2e/baselines/ and are generated by
script_utils/generate_e2e_baselines.py.  Each test calls the helpers
here to load reference data and assert outputs are within tolerance.
"""

from __future__ import annotations

import json
