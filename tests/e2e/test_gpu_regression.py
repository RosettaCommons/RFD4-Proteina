# ── Inference & beam search tests ─────────────────────────────────────────────


@pytest.mark.gpu
@pytest.mark.regression
@pytest.mark.slow
def test_inference_regression(inference_out: Path) -> None:
    """Generate M0664_2dhn; designed CIF matches baseline."""
    baseline_dir = BASELINES_DIR / "inference"
    designed = find_inference_cif(inference_out, REGRESSION_EXAMPLE_ID, "generated")
    rmsd_d = all_atom_rmsd(designed, baseline_dir / "designed.cif")
    assert (
        rmsd_d <= BASELINE_RMSD_ATOL_TIGHT
    ), f"Designed structure all-atom RMSD {rmsd_d:.4f} Å exceeds {BASELINE_RMSD_ATOL_TIGHT} Å"


@pytest.mark.gpu
@pytest.mark.regression
@pytest.mark.slow
def test_beam_search_regression() -> None:
    """Minimal beam search on monomer-short; designed structure matches baseline."""
    require_gpu_e2e(min_gpus=1)
    require_l40s()
    require_sota_ckpt()

    baseline_dir = BASELINES_DIR / "beam_search"
    baseline_cifs = sorted(baseline_dir.glob("*_generated.cif"))
    if not baseline_cifs:
        pytest.skip("Beam search baselines not generated yet.")

    out_dir = _run_beam_search("regression_beam_search")
    observed_cifs = find_beam_search_cifs(out_dir)

    def _strip_hash(name: str) -> str:
        """Strip the machine-dependent dataset-hash prefix (e.g. 'd8a1e1ef__')."""
        _, _, rest = name.partition("__")
        return rest or name

    # Every baseline CIF must have a matching output CIF.
    # Match on the part after the dataset-hash prefix, which is machine-dependent.
    for bl_cif in baseline_cifs:
        obs_matches = [c for c in observed_cifs if _strip_hash(c.name) == _strip_hash(bl_cif.name)]
        assert obs_matches, f"Beam search output missing expected CIF: {bl_cif.name}"
        rmsd = all_atom_rmsd(obs_matches[0], bl_cif)
        assert rmsd <= BASELINE_RMSD_ATOL_TIGHT, (
            f"Beam search {bl_cif.name}: all-atom RMSD {rmsd:.4f} Å exceeds " f"{BASELINE_RMSD_ATOL_TIGHT} Å"
        )
