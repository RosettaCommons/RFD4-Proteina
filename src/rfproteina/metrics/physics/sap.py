"""Hydrogen-free approximations of Rosetta SAP developability scores.

The implementation follows Rosetta's accurate SAP calculation while operating
directly on Biotite ``AtomArray`` objects. ProtOr radii account for implicit
hydrogens during SASA calculation; no hydrogen coordinates are constructed.
"""

