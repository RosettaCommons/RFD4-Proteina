def _heavy_atoms(atom_array: AtomArray) -> AtomArray:
    """Return atoms with finite coordinates, excluding explicit hydrogens."""
    if atom_array.array_length() == 0:
        return atom_array
    finite = np.isfinite(atom_array.coord).all(axis=-1)
    heavy = ~np.isin(np.char.upper(atom_array.element.astype(str)), HYDROGEN_LIKE_SYMBOLS)
    return atom_array[finite & heavy]


def _one_letter_per_atom(atom_array: AtomArray) -> np.ndarray:
    return np.array([_AA3_TO_1.get(name, "") for name in atom_array.res_name], dtype="U1")


def _sidechain_mask(atom_array: AtomArray, one_letter: np.ndarray) -> np.ndarray:
    is_standard = np.isin(one_letter, list(SAP_HYDROPHOBICITY))
    is_backbone = np.isin(atom_array.atom_name, list(_BACKBONE_ATOMS))
    return is_standard & ~is_backbone


def _center_multiplicity(atom_array: AtomArray, one_letter: np.ndarray, center_indices: np.ndarray) -> np.ndarray:
    return np.array(
        [
            _IMPLICIT_CENTER_MULTIPLICITY.get(one_letter[index], {}).get(atom_array.atom_name[index], 1)
            for index in center_indices
        ],
        dtype=float,
    )


def calculate_sap(
    atom_array: AtomArray,
    *,
    probe_radius: float = 1.1,
    point_number: int = 162,
    distance_cutoff: float = 5.0,
    implicit_hydrogen_centers: bool = True,
    implicit_backbone_hydrogen_centers: bool = True,
    score_mask: str | None = None,
) -> float:
    """Approximate Rosetta's accurate spatial aggregation propensity (SAP).

    Args:
        atom_array: Protein structure. Standard amino acids contribute to SAP;
            all heavy atoms occlude solvent.
        probe_radius: SASA probe radius in Angstrom. Rosetta SAP uses 1.1 A.
        point_number: Number of Shrake-Rupley sphere points. Rosetta's LeGrand
            implementation uses 162 points.
        distance_cutoff: Side-chain neighborhood radius in Angstrom.
        implicit_hydrogen_centers: Weight each heavy-atom neighborhood by the
            number of explicit centers it represents in a hydrogenated pose.
        implicit_backbone_hydrogen_centers: Add virtual H and HA neighborhood
            centers at N and CA coordinates. Rosetta's atom-index iteration
            includes these backbone hydrogens for every non-glycine residue.
        score_mask: Optional atom query selecting scored centers. All input atoms
            still contribute solvent occlusion and neighboring hydrophobicity.

    Returns:
        SAP score, or NaN for an empty selection.
    """
    atoms = _heavy_atoms(atom_array)
    if atoms.array_length() == 0:
        return float("nan")

    selected = np.ones(len(atoms), dtype=bool) if score_mask is None else resolve_mask(atoms, score_mask)
    if not selected.any():
        return float("nan")

    one_letter = _one_letter_per_atom(atoms)
    sidechain = _sidechain_mask(atoms, one_letter)
    sidechain_center_indices = np.flatnonzero(sidechain)
    if sidechain_center_indices.size == 0:
        return 0.0

    atom_sasa = calculate_atomwise_sasa(
        atoms,
        probe_radius=probe_radius,
        atom_radii="auto",
        point_number=point_number,
    )
    hydrophobicity = np.array([SAP_HYDROPHOBICITY.get(aa, 0.0) for aa in one_letter], dtype=float)
    max_sasa = np.array([SAP_MAX_SIDECHAIN_SASA.get(aa, np.inf) for aa in one_letter], dtype=float)
    backbone_hydrogen_parents = (
        np.isin(atoms.atom_name, ["N", "CA"]) & np.isin(one_letter, list(SAP_HYDROPHOBICITY)) & (one_letter != "G")
    )
    atom_contribution = np.zeros(atoms.array_length(), dtype=float)
    atom_contribution[sidechain] = atom_sasa[sidechain] * hydrophobicity[sidechain] / max_sasa[sidechain]

    center_indices = sidechain_center_indices
    center_multiplicity = np.ones(center_indices.size, dtype=float)
    if implicit_hydrogen_centers:
        center_multiplicity = _center_multiplicity(atoms, one_letter, center_indices)

    if implicit_backbone_hydrogen_centers:
        virtual_center_indices = np.flatnonzero(backbone_hydrogen_parents)
        center_indices = np.concatenate([center_indices, virtual_center_indices])
        center_multiplicity = np.concatenate([center_multiplicity, np.ones(virtual_center_indices.size)])

    cell_list = CellList(atoms, cell_size=distance_cutoff, selection=sidechain)
    neighbors = cell_list.get_atoms(atoms.coord[center_indices], radius=distance_cutoff)
    valid = neighbors >= 0
    safe_neighbors = np.where(valid, neighbors, 0)
    strict_cutoff = (
        np.sum(
            (atoms.coord[safe_neighbors] - atoms.coord[center_indices, None, :]) ** 2,
            axis=-1,
        )
        < distance_cutoff**2
    )
    local_sap = np.sum(atom_contribution[safe_neighbors] * valid * strict_cutoff, axis=1)
    local_sap = np.maximum(local_sap, 0.0)

    local_sap *= center_multiplicity
    return float(SAP_ROSETTA_SCALE * np.sum(local_sap[selected[center_indices]]))


def calculate_exposed_hydrophobics(
    atom_array: AtomArray,
    *,
    sasa_cutoff: float = 20.0,
    probe_radius: float = 2.0,
    point_number: int = 162,
) -> float:
    """Approximate Rosetta's ``ExposedHydrophobicsFilter`` score.

    Only N, CA, C, O, and CB atoms are used as surfaces and occluders. The
    result is the sum of ``max(0, residue_sasa - sasa_cutoff)`` over M, L, I,
    V, F, A, W, and Y residues.
    """
    atoms = _heavy_atoms(atom_array)
    if atoms.array_length() == 0:
        return float("nan")

    one_letter = _one_letter_per_atom(atoms)
    sasa_atoms = np.isin(atoms.atom_name, list(_EXPOSED_SASA_ATOMS)) & (one_letter != "")
    atom_sasa = calculate_atomwise_sasa(
        atoms,
        probe_radius=probe_radius,
        atom_radii="auto",
        point_number=point_number,
        occlusion_mask=sasa_atoms,
    )

    residue_start = np.flatnonzero(
        np.r_[
            True,
            (atoms.chain_id[1:] != atoms.chain_id[:-1])
            | (atoms.res_id[1:] != atoms.res_id[:-1])
            | (atoms.ins_code[1:] != atoms.ins_code[:-1]),
        ]
    )
    residue_sasa = np.add.reduceat(np.nan_to_num(atom_sasa, nan=0.0), residue_start)
    residue_aa = one_letter[residue_start]
    hydrophobic = np.isin(residue_aa, list(_EXPOSED_HYDROPHOBIC_RESIDUES))
    raw_score = np.maximum(residue_sasa[hydrophobic] - sasa_cutoff, 0.0).sum()
    return float(EXPOSED_HYDROPHOBICS_ROSETTA_SCALE * raw_score)
