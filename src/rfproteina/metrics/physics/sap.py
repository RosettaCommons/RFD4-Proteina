# SAP scale fitted on a preassigned calibration split and validated on 13 held-out structures
# (Pearson r=0.998, MAE=5.8).
SAP_ROSETTA_SCALE = 0.8609677892948379
# Exposed-hydrophobics fit excludes unresolved N/CA/C/O/CB coordinates, which
# PyRosetta reconstructs during import but an AtomArray does not contain.
EXPOSED_HYDROPHOBICS_ROSETTA_SCALE = 1.0740459414622847

_AA3_TO_1 = aa_chem_comp_3to1(standard_only=True)
_BACKBONE_ATOMS = frozenset(["N", "CA", "C", "O", "OXT"])
_EXPOSED_HYDROPHOBIC_RESIDUES = frozenset("MLIVFAWY")
_EXPOSED_SASA_ATOMS = frozenset(["N", "CA", "C", "O", "CB"])

